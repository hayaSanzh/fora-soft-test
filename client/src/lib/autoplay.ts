/**
 * Политика автозапуска: запуск воспроизведения и распознавание блокировки
 * (задача IP 11.5, ФТ-37, US-13, TDD §4.7, §8.1, риск R6).
 *
 * Браузер не даёт запускать медиа со звуком без жеста пользователя. Клик «Войти»
 * жестом является, поэтому в Chrome/Firefox/Edge звук обычно стартует сам — но
 * рассчитывать на это нельзя: правило зависит от браузера, настроек сайта и
 * Media Engagement Index. Если `play()` отклонён политикой, поднимается оверлей
 * «Включить звук», и один клик по нему повторяет `play()` для всех элементов.
 *
 * Логика вынесена из React в чистый модуль: её нужно проверять без jsdom, а
 * поведение здесь тонкое и ломается молча.
 *
 * ★ Два правила, каждое из которых легко нарушить «очевидным» решением:
 *
 * 1. **Блокировкой считается только `NotAllowedError`.** `play()` отклоняется и
 *    по совершенно штатным причинам — самая частая `AbortError`: предыдущий
 *    `play()` прерван новым присвоением `srcObject`. Если считать блокировкой
 *    любую ошибку, оверлей «Включить звук» будет выскакивать при каждой смене
 *    потока, хотя звук работает.
 * 2. **Заглушать элемент запрещено.** Популярный «фикс» автозапуска — выставить
 *    `muted = true`, ведь без звука воспроизведение разрешено всегда. Здесь это
 *    означало бы, что участники видят друг друга, но не слышат (ФТ-19), причём
 *    молча и без единой ошибки в консоли. Заглушён только self-view (эхо).
 */

/** Минимальный контракт: в тестах вместо `<video>` подставляется заглушка. */
export interface PlayableMedia {
  play: () => Promise<void>;
}

/** Отклонил ли браузер воспроизведение именно по политике автозапуска. */
export function isAutoplayBlocked(error: unknown): boolean {
  if (typeof error !== 'object' || error === null) return false;
  return (error as { name?: unknown }).name === 'NotAllowedError';
}

/**
 * Пытается запустить воспроизведение. Возвращает `true`, если помешала политика
 * автозапуска, — то есть нужен жест пользователя.
 *
 * Не бросает исключений: неудачный `play()` не должен ломать привязку потока.
 */
export async function tryPlay(media: PlayableMedia): Promise<boolean> {
  try {
    await media.play();
    return false;
  } catch (error) {
    return isAutoplayBlocked(error);
  }
}

/**
 * Повторяет воспроизведение для всех элементов. Возвращает `true`, если ни один
 * больше не заблокирован (тогда оверлей можно убрать).
 *
 * ★ `play()` вызывается для всех элементов **синхронно**, до первого `await`:
 * разрешение действует на время обработки жеста, и последовательное
 * `await tryPlay(...)` в цикле потеряло бы его — со второго элемента звука бы не
 * было. Поэтому сначала создаются все промисы, и только потом ожидаются.
 */
export async function resumePlayback(list: Iterable<PlayableMedia>): Promise<boolean> {
  const attempts = [...list].map((media) => tryPlay(media));
  const results = await Promise.all(attempts);
  return results.every((blocked) => !blocked);
}

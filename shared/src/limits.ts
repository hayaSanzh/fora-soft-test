/**
 * Числовые лимиты контракта (задача IP 2.3).
 *
 * Живут в `shared/`, потому что должны совпадать в трёх местах: схемах
 * валидации, серверной конфигурации и клиентском UI (счётчик символов,
 * `maxLength` у поля ввода). Один и тот же литерал, размноженный по коду, —
 * гарантированный источник расхождения между клиентом и сервером.
 *
 * Значения переопределяются переменными окружения (TDD §12.5); схемы
 * принимают лимит параметром, поэтому переопределение реально работает.
 */

/** ФТ-38: имя участника ≤ 30 символов. Q6/Q7 закрыты (TDD §14.2). */
export const DEFAULT_MAX_NAME_LEN = 30;

/** Q7: лимит длины сообщения чата (ФТ-40). */
export const DEFAULT_MAX_MESSAGE_LEN = 500;

/** Q8: глубина истории чата — ring buffer комнаты (TDD §4.2). */
export const DEFAULT_MAX_MESSAGES = 200;

/** Лимит участников: следствие mesh-топологии, не UX-решение (TDD §9.2). */
export const DEFAULT_MAX_PARTICIPANTS = 4;

/**
 * `roomId` из URL (TDD §5.3). Валидация нужна не «для красоты»: без неё в
 * `Map` комнат попадут мусорные и path-подобные ключи.
 */
export const ROOM_ID_PATTERN = /^[A-Za-z0-9_-]{4,64}$/;

/** Длина `nanoid` для `roomId` ≈ 71 бит энтропии (TDD §10.1). */
export const ROOM_ID_LENGTH = 12;

/** Длина `nanoid` для `messageId` (TDD §5.3). */
export const MESSAGE_ID_LENGTH = 10;

/**
 * Классы символов собраны из строк с escape-последовательностями намеренно:
 * литерал регулярного выражения содержал бы невидимые символы прямо в исходнике,
 * и такой код невозможно ни прочитать, ни отревьюить.
 */

/**
 * Управляющие символы. `\t` (0x09), `\n` (0x0A) и `\r` (0x0D) сюда **не входят**:
 * в тексте сообщения перевод строки легитимен, а в имени он сворачивается в
 * пробел (иначе «Аня\nПетрова» превратилась бы в «АняПетрова»).
 */
const CONTROL_CHARS = '\\u0000-\\u0008\\u000B\\u000C\\u000E-\\u001F\\u007F';

/**
 * Zero-width — отдельный случай: символы невидимы, но позволяют получить два
 * визуально одинаковых имени или «пустое» имя, прошедшее проверку длины.
 */
const ZERO_WIDTH_CHARS = '\\u200B-\\u200D\\u2060\\uFEFF';

/** Вырезается из имени участника (TDD §10.3). */
export const INVISIBLE_CHARS_PATTERN = new RegExp(`[${CONTROL_CHARS}${ZERO_WIDTH_CHARS}]`, 'gu');

/** Вырезается из текста сообщения чата (TDD §10.3). */
export const CONTROL_CHARS_PATTERN = new RegExp(`[${CONTROL_CHARS}]`, 'gu');
